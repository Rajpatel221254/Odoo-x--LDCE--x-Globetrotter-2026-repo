/**
 * Intelligently picks a relevant image based on text content & location,
 * or selects a rotating unique image from the pool to prevent repetition.
 */
let lastSelectedIndex = 0;

export const getSmartStoryImage = (text = '', location = '', fallbackIndex = null) => {
  const combined = `${text} ${location}`.toLowerCase();

  // Search through all category images for keyword match
  for (const item of ALL_TRAVEL_IMAGES) {
    if (item.keywords && item.keywords.some((kw) => combined.includes(kw))) {
      return item.url;
    }
  }

  // If no specific keyword matched, cycle through the entire pool sequentially
  // so each new post gets a completely different image
  const index =
    typeof fallbackIndex === 'number'
      ? fallbackIndex % ALL_TRAVEL_IMAGES.length
      : (++lastSelectedIndex) % ALL_TRAVEL_IMAGES.length;

  return ALL_TRAVEL_IMAGES[index].url;
};

/**
 * Returns a random travel image different from the current one.
 */
export const getRandomTravelImage = (currentUrl = '') => {
  const pool = ALL_TRAVEL_IMAGES.filter((img) => img.url !== currentUrl);
  if (!pool.length) return ALL_TRAVEL_IMAGES[0].url;
  const randomIndex = Math.floor(Math.random() * pool.length);
  return pool[randomIndex].url;
};

